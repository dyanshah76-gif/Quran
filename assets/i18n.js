const AR_DIGITS = ['٠', '١', '٢', '٣', '٤', '٥', '٦', '٧', '٨', '٩'];
export const arabicDigits = (n) => String(n).replace(/\d/g, (d) => AR_DIGITS[Number(d)]);

const versesFr = (n) => (n > 1 ? `${n} versets` : `${n} verset`);
const versesEn = (n) => (n > 1 ? `${n} ayahs` : `${n} ayah`);
const versesRur = (n) => (n > 1 ? `${n} ayaat` : `${n} ayat`);
const versesAr = (n) => {
  if (n === 1) return 'آية واحدة';
  if (n === 2) return 'آيتان';
  const rest = n % 100;
  return rest >= 3 && rest <= 10 ? `${arabicDigits(n)} آيات` : `${arabicDigits(n)} آية`;
};

